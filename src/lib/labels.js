/** وصف عربي لنوع العملية. */
export function describeType(type) {
  return type === 'manual_journal'
    ? 'قيد محاسبي'
    : type === 'purchase_bill'
      ? 'فاتورة مشتريات'
      : type === 'sales_invoice'
        ? 'فاتورة مبيعات'
        : type;
}
