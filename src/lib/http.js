/**
 * ملخّص ردّ خطأ من واجهة برمجية، صالحاً لرسالة محادثة.
 *
 * ردّ الخطأ قد يكون صفحة HTML كاملة أو JSON طويلاً، وكلاهما يُغرق رسالة
 * المستخدم ويُربك محلّل تليجرام. نُبقي أوّل ما يدلّ على السبب فقط.
 */
export function briefApiError(body, limit = 220) {
  const text = String(body || '')
    .replace(/<[^>]*>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  return text.length > limit ? `${text.slice(0, limit)}…` : text;
}
