// الخروج من جلسة المنصة — في الحزمة، ووجهته المركز.
//
// ليس في وثيقة الربط، وأُضيف لأن زرّ «تسجيل الخروج» قائم في اللوحة.
//
// وكان تنفيذاً محلياً يحذف الجلسة من KV ويمسح الكوكي ثم يحوّل إلى `/`.
// والحذف والمسح يقعان فعلاً، ولا أثر يراه المستخدم: جذر المنصة محميّ،
// فيحوّله الوسيط إلى `/go/NAF-Accountant`، وجلسة المركز لم تُمسّ فتُصدر
// رمزاً جديداً — فيعود الخارجُ إلى شاشته قبل أن يقرأ شيئاً، فيقرأ من ذلك
// أن الزرّ لا يعمل.
//
// و`handleLogout` وجهته `{issuer}/`، خارج السياج. وشكل ردّه يتبع طبيعة
// الطلب: ٣٠٢ للتنقّل، و`{ ok, next }` لنداء `fetch` — والثاني لازم لأن
// المتصفّح لا يتبع تحويلةً إلى أصل آخر في `fetch` بلا CORS، فكانت اللوحة
// تتبع التحويلة إلى `/` فتأخذ ٤٠١ بجسم JSON لا يعنيها.
//
// وهذا خروج من هذه المنصة وحدها، لا من المركز — والدخول التالي يمرّ به.
// ============================================================================

import { handleLogout } from 'naf-auth';
import { authConfig } from './config.js';

export const ssoLogout = (c) => handleLogout(c.req.raw, c.env, authConfig(c.env));
