// وسيط الدخول الموحّد — يستورد وسيط الحزمة ولا يعيد بناء شيء منه.
//
// يحوّل غير المسجَّل إلى المركز، ويرفض الموقوف محلياً، ويحقن
// `{ id, role, perms }` في سياق الطلب. والمسارات تقرأه من `c.get('user')`.
// ============================================================================

import { honoMiddleware, timingSafeEqual } from 'naf-auth';
import { authConfig } from './config.js';

/**
 * المفتاح الآلي يمرّ قبل الوسيط.
 *
 * `DASHBOARD_API_KEY` استعمال آليّ قائم — مزامنة و curl وأتمتة — لا متصفّح
 * فيه ولا كوكي، فلا معنى لتحويله إلى المركز. وبلا هذا الاستثناء تنكسر كل
 * أتمتة تعتمده، وهو انحدار في وظيفة قائمة.
 *
 * والمقارنة زمنية ثابتة، والمفتاح من الأسرار لا من الكود.
 * وما بعده يُعامَل في `authenticate` كما كان: مسؤولاً آلياً.
 */
function isMachineKey(c) {
  const key = c.env.DASHBOARD_API_KEY;
  if (!key) return false;
  const token = (c.req.header('Authorization') || '').replace(/^Bearer\s+/i, '').trim();
  return !!token && timingSafeEqual(token, key);
}

export const ssoMiddleware = (c, next) => {
  if (isMachineKey(c)) return next();
  return honoMiddleware(authConfig(c.env))(c, next);
};

/** الطرق التي لا تغيّر شيئاً. وما عداها كتابة. */
const READ_METHODS = new Set(['GET', 'HEAD', 'OPTIONS']);

/**
 * القارئ يقرأ ولا يكتب.
 *
 * المنصة كانت تعرض ثلاثة أدوار وتنفّذ اثنين: الفحص `role !== 'admin'` في
 * ثلاثة مواضع، ولا ذكر لـ`viewer` ولا لـ`editor` في أي مسار. فمن حمل
 * «مستخدم (اطّلاع)» كان يكتب العمليات ويحذفها ويزامن شجرة الحسابات —
 * والاسم يقول غير ذلك، ومسؤول المنصة يسنِده ظانّاً أنه يمنع الكتابة.
 *
 * **والحكم بالطريقة لا بقائمة المسارات.** قائمةٌ تُعدَّد فيها المسارات
 * الكاتبة تنسى واحداً أوّل ما يُضاف مسار، ونسيانها ثغرة صامتة. والطريقة
 * تشمل ما لم يُكتب بعد.
 *
 * ولا يمسّ المفتاح الآلي: `ssoMiddleware` يمرّره قبل أن يُقرأ دورٌ أصلاً،
 * فلا مستخدم في السياق — وأتمتةٌ قائمة لا تُكسر بحارس أُضيف للبشر.
 *
 * ولا يمسّ `‎/auth/logout`: مسارٌ عامّ لا يمرّ به مستخدم محقون، فيخرج
 * القارئ كما يخرج غيره.
 */
export const requireWriter = (c, next) => {
  const user = c.get('user');
  if (user?.role === 'viewer' && !READ_METHODS.has(c.req.method)) {
    // §١٠ · رسائل الصلاحية — «تحرير» لا «مسؤول»: ما رُدّ عنه القارئ يفعله
    // المحرّر، فقولُ «مسؤول» يدفعه إلى طلب ترقيةٍ لا يحتاجها.
    return c.json({ ok: false, error: 'هذه العملية تتطلب صلاحية تحرير' }, 403);
  }
  return next();
};
