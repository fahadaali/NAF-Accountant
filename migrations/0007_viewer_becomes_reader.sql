-- ============================================================
-- `viewer` يصير قارئاً فعلاً — ومن يحمله اليوم يُرفع إلى `editor`.
-- ============================================================

-- المنصة تعرض ثلاثة أدوار وتنفّذ اثنين: الفحص `role !== 'admin'` في ثلاثة
-- مواضع، ولا ذكر لـ`viewer` ولا لـ`editor` في أي مسار. فمن حمل «مستخدم
-- (اطّلاع)» كان يكتب العمليات ويحذفها ويزامن شجرة الحسابات.
--
-- ومع هذه الهجرة يصير الاسم صادقاً: حارسٌ في `src/auth/middleware.js` يمنع
-- الكتابة عن `viewer`.
--
-- **وهذا السطر يسبق نشرَ الحارس ولا يتأخّر عنه.** الدور الافتراضي `viewer`،
-- فكلُّ من دخل ولم يُرقَّ يحمله. وتشغيلُ الحارس قبله ينزع الكتابة منهم
-- جميعاً في لحظة واحدة.
--
-- فيُرفعون إلى `editor` — وهو ما كانوا يملكونه فعلاً، فلا أحد يفقد شيئاً
-- ولا أحد يُمنح ما لم يكن له. و`viewer` يبقى لمن يُسنَد إليه بعد اليوم.
--
-- ولا نشرَ آليّ في هذا المستودع، فتُشغَّل باليد قبل النشر:
--   npm run db:migrate   (يشمل هذا الملف وكل ما سبقه)
--
-- وتعمل مكرّرة بلا أثر: بعد أوّل تشغيل لا صفّ `viewer` يطابقها.
UPDATE members SET role = 'editor' WHERE role = 'viewer';
